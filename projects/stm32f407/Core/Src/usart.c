/* UART RX callback type */
typedef void (*uart_rx_callback_t)(const uint8_t *data, uint32_t size);
static uart_rx_callback_t s_uart3_rx_callback = NULL;

void uart3_register_rx_callback(uart_rx_callback_t callback)
{
    s_uart3_rx_callback = callback;
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART3) {
        if (s_uart3_rx_callback != NULL) {
            uint8_t received_byte = USART3->DR;
            s_uart3_rx_callback(&received_byte, 1);
        }
        HAL_UART_Receive_IT(&huart3, s_usart3_rx_buf, 1);
    }
    (void)huart;
}

